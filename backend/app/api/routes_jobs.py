"""FastAPI REST & Streaming Routes for Async Job Runner.

Endpoints:
- GET /api/jobs: list jobs with status, accelerator, duration.
- POST /api/jobs: submit job payload.
- GET /api/jobs/{id}: job details.
- GET /api/jobs/{id}/logs: live log streaming or text download.
- GET /api/jobs/{id}/output: download output notebook.
- POST /api/jobs/{id}/cancel: cancel running or queued job.
"""

from __future__ import annotations

import os
from typing import List, Optional

from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from fastapi.responses import FileResponse, PlainTextResponse, StreamingResponse

from backend.app.core.models import JobCreate, JobResponse
from backend.app.core.security import get_current_admin
from backend.app.services.job_runner import job_runner_service

router = APIRouter(prefix="/api/jobs", tags=["jobs"])


@router.get("", response_model=List[JobResponse])
async def list_jobs(
    status: Optional[str] = Query(None, description="Filter jobs by status"),
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    admin=Depends(get_current_admin),
):
    """List submitted jobs with pagination and optional status filter."""
    return job_runner_service.list_jobs(status=status, limit=limit, offset=offset)


@router.post("", response_model=JobResponse, status_code=status.HTTP_201_CREATED)
async def submit_job(
    payload: JobCreate,
    admin=Depends(get_current_admin),
):
    """Submit a new .py, .ipynb, or shell job for execution."""
    return await job_runner_service.submit_job(payload)


@router.get("/{job_id}", response_model=JobResponse)
async def get_job_detail(
    job_id: str,
    admin=Depends(get_current_admin),
):
    """Retrieve details and execution status for a specific job."""
    job = job_runner_service.get_job(job_id)
    if not job:
        raise HTTPException(status_code=404, detail=f"Job {job_id} not found")
    return job


@router.get("/{job_id}/logs")
async def get_job_logs(
    job_id: str,
    follow: bool = Query(False, description="Stream real-time log output"),
    admin=Depends(get_current_admin),
):
    """Retrieve or stream live logs from /data/jobs/{job_id}/run.log."""
    job = job_runner_service.get_job(job_id)
    if not job:
        raise HTTPException(status_code=404, detail=f"Job {job_id} not found")

    if follow:
        return StreamingResponse(
            job_runner_service.stream_logs(job_id, follow=True),
            media_type="text/plain; charset=utf-8",
        )

    log_path = job.log_path
    if not os.path.exists(log_path):
        return PlainTextResponse("Log file not created yet.")

    with open(log_path, "r", encoding="utf-8", errors="replace") as f:
        content = f.read()
    return PlainTextResponse(content)


@router.get("/{job_id}/output")
async def download_output_notebook(
    job_id: str,
    admin=Depends(get_current_admin),
):
    """Download the output .ipynb notebook generated by notebook execution."""
    job = job_runner_service.get_job(job_id)
    if not job:
        raise HTTPException(status_code=404, detail=f"Job {job_id} not found")

    if job.job_type != "notebook":
        raise HTTPException(status_code=400, detail="Job is not of type 'notebook'")

    out_path = job.output_notebook_path
    if not out_path or not os.path.exists(out_path):
        raise HTTPException(
            status_code=404,
            detail=f"Output notebook for job {job_id} is not yet available (status: {job.status})",
        )

    return FileResponse(
        out_path,
        media_type="application/x-ipynb+json",
        filename=f"{job_id}_output.ipynb",
    )


@router.post("/{job_id}/cancel")
async def cancel_job(
    job_id: str,
    admin=Depends(get_current_admin),
):
    """Cancel a queued or running job."""
    job = job_runner_service.get_job(job_id)
    if not job:
        raise HTTPException(status_code=404, detail=f"Job {job_id} not found")

    cancelled = await job_runner_service.cancel_job(job_id)
    if not cancelled:
        raise HTTPException(
            status_code=400,
            detail=f"Cannot cancel job in state '{job.status}'",
        )

    return {"status": "CANCELLED", "id": job_id}
